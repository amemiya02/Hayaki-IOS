//! Generates Swift code from the descriptor set written by the core's build.
//!
//! Usage: hayaki_codegen <descriptors.bin> <output-folder>
//!
//! Writes two files into the folder:
//!
//! - `CoreMethods.swift`: the service and method number of every method.
//! - `CoreCalls.swift`: a typed `CoreCall` and a typed async `CoreClient`
//!   method for every method, with the request and response message types
//!   named in the descriptor set.
//!
//! Service and method numbers are taken from upstream's own
//! `anki_proto_gen::get_services`, the same helper the core uses to dispatch
//! calls, so they always match the built library. Nothing is numbered by hand.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anki_proto_gen::get_services;
use anki_proto_gen::BackendService;
use anki_proto_gen::Method;
use anyhow::Context;
use anyhow::Result;
use prost_reflect::DescriptorPool;
use prost_reflect::MessageDescriptor;

const HEADER: &str = "// Generated by core/codegen from the Anki core's descriptor set. Do not edit.\n\
                      // Regenerate with scripts/build-core.sh.\n";

/// Names already used by the hand-written parts of `CoreClient` and `CoreCall`.
/// A core method with one of these names would shadow them, so generation
/// stops instead.
const RESERVED_NAMES: &[&str] = &[
    "abort",
    "call",
    "decode",
    "encodedRequest",
    "execute",
    "init",
    "method",
    "perform",
    "poll",
    "replaceBackend",
    "request",
    "start",
];

/// Swift keywords that a lower-camel-cased method name could collide with.
const SWIFT_KEYWORDS: &[&str] = &[
    "associatedtype", "break", "case", "catch", "class", "continue", "default", "defer", "deinit",
    "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for", "func",
    "guard", "if", "import", "in", "init", "inout", "internal", "is", "let", "nil", "open",
    "operator", "private", "protocol", "public", "repeat", "rethrows", "return", "self", "Self",
    "static", "struct", "subscript", "super", "switch", "throw", "throws", "true", "try",
    "typealias", "var", "where", "while",
];

fn main() -> Result<()> {
    let args: Vec<String> = env::args().collect();
    let [_, descriptors, output] = args.as_slice() else {
        anyhow::bail!("usage: hayaki_codegen <descriptors.bin> <output-folder>");
    };
    let bytes = fs::read(descriptors).with_context(|| format!("reading {descriptors}"))?;
    let pool = DescriptorPool::decode(bytes.as_slice()).context("decoding descriptor set")?;
    let (_, services) = get_services(&pool);
    let output = Path::new(output);
    fs::create_dir_all(output).with_context(|| format!("creating {}", output.display()))?;
    write_if_changed(&output.join("CoreMethods.swift"), &render_methods(&services))?;
    write_if_changed(&output.join("CoreCalls.swift"), &render_calls(&services)?)?;
    Ok(())
}

fn write_if_changed(path: &Path, contents: &str) -> Result<()> {
    if fs::read_to_string(path).ok().as_deref() != Some(contents) {
        fs::write(path, contents).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

/// `BackendDecksService` becomes `Decks`.
fn service_name(service: &BackendService) -> &str {
    service
        .name
        .trim_start_matches("Backend")
        .trim_end_matches("Service")
}

fn render_methods(services: &[BackendService]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "\n/// One method of the Anki core, addressed by the numbers the core dispatches on.\n\
         public struct CoreMethod: Sendable, Hashable, CustomStringConvertible {\n    \
         public let service: UInt32\n    \
         public let method: UInt32\n    \
         public let name: String\n\n    \
         public var description: String { name }\n}\n\n\
         extension CoreMethod {\n",
    );
    for service in services {
        let service_name = service_name(service);
        writeln!(out, "    public enum {service_name} {{").unwrap();
        for method in service.all_methods() {
            writeln!(
                out,
                "        public static let {swift_name} = CoreMethod(service: {service_index}, method: {method_index}, name: \"{service_name}.{proto_name}\")",
                swift_name = escape_keyword(&lower_camel(method.proto.name())),
                service_index = service.index,
                method_index = method.index,
                proto_name = method.proto.name(),
            )
            .unwrap();
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    out
}

/// One typed call per core method. Calls are flat (no service prefix), so a
/// name used by two services would be ambiguous; that stops generation.
fn render_calls(services: &[BackendService]) -> Result<String> {
    let mut by_name: BTreeMap<String, (&BackendService, &Method)> = BTreeMap::new();
    for service in services {
        for method in service.all_methods() {
            let name = lower_camel(method.proto.name());
            if RESERVED_NAMES.contains(&name.as_str()) {
                anyhow::bail!("core method {} clashes with a hand-written name", method.proto.full_name());
            }
            if let Some((other, _)) = by_name.insert(name.clone(), (service, method)) {
                anyhow::bail!(
                    "core method {name} exists in both {} and {}",
                    other.name,
                    service.name
                );
            }
        }
    }

    let mut calls = String::new();
    let mut client = String::new();
    for service in services {
        for method in service.all_methods() {
            render_call(&mut calls, &mut client, service, method);
        }
    }

    let mut out = String::from(HEADER);
    out.push_str("\nimport AnkiProto\n\n");
    out.push_str("// Every method of the core as a typed call, to run with CoreClient.perform(_:)\n");
    out.push_str("// or, for a long operation, CoreClient.start(_:).\n");
    out.push_str("extension CoreCall {\n");
    out.push_str(&calls);
    out.push_str("}\n\n");
    out.push_str("// Every method of the core as a typed async method of the Core Client.\n");
    out.push_str("extension CoreClient {\n");
    out.push_str(&client);
    out.push_str("}\n");
    Ok(out)
}

fn render_call(calls: &mut String, client: &mut String, service: &BackendService, method: &Method) {
    let name = escape_keyword(&lower_camel(method.proto.name()));
    let constant = format!(
        "CoreMethod.{}.{}",
        service_name(service),
        escape_keyword(&lower_camel(method.proto.name()))
    );
    let response = swift_type(&method.proto.output());
    let docs = doc_comment(method);

    // Requests of type generic.Empty take no argument.
    let (parameter, argument, request) = match method.input() {
        Some(input) => (
            format!("_ request: {}", swift_type(&input)),
            "request",
            "request".to_string(),
        ),
        None => (String::new(), "", "Anki_Generic_Empty()".to_string()),
    };

    write!(calls, "{docs}").unwrap();
    writeln!(calls, "    public static func {name}({parameter}) -> CoreCall<{response}> {{").unwrap();
    writeln!(calls, "        CoreCall<{response}>({constant}, {request})").unwrap();
    writeln!(calls, "    }}\n").unwrap();

    // Responses of type generic.Empty return nothing.
    write!(client, "{docs}").unwrap();
    if method.output().is_some() {
        writeln!(client, "    public func {name}({parameter}) async throws(CoreError) -> {response} {{").unwrap();
        writeln!(client, "        try await perform(.{name}({argument}))").unwrap();
    } else {
        writeln!(client, "    public func {name}({parameter}) async throws(CoreError) {{").unwrap();
        writeln!(client, "        _ = try await perform(.{name}({argument}))").unwrap();
    }
    writeln!(client, "    }}\n").unwrap();
}

fn doc_comment(method: &Method) -> String {
    let mut out = String::new();
    if let Some(comments) = &method.comments {
        for line in comments.lines() {
            let line = line.trim_end();
            if line.is_empty() {
                out.push_str("    ///\n");
            } else {
                writeln!(out, "    /// {}", line.trim_start()).unwrap();
            }
        }
        out.push_str("    ///\n");
    }
    writeln!(
        out,
        "    /// Core method `{}`.",
        method.proto.full_name()
    )
    .unwrap();
    out
}

/// The Swift name protoc-gen-swift gives a message: the package in upper camel
/// case joined by underscores, then the message, with nested messages as
/// nested types. `anki.import_export.ImportResponse.Log` becomes
/// `Anki_ImportExport_ImportResponse.Log`.
fn swift_type(message: &MessageDescriptor) -> String {
    let package = message.package_name();
    let prefix: Vec<String> = package.split('.').map(upper_camel).collect();
    let local = message
        .full_name()
        .strip_prefix(package)
        .and_then(|rest| rest.strip_prefix('.'))
        .unwrap_or(message.full_name());
    format!("{}_{}", prefix.join("_"), local)
}

/// `import_export` becomes `ImportExport`.
fn upper_camel(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect(),
                None => String::new(),
            }
        })
        .collect()
}

fn lower_camel(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_lowercase().chain(chars).collect(),
        None => String::new(),
    }
}

fn escape_keyword(name: &str) -> String {
    if SWIFT_KEYWORDS.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_string()
    }
}

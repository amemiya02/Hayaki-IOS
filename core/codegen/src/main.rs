//! Generates Swift code from the descriptor set written by the core's build.
//!
//! Usage: hayaki_codegen <descriptors.bin> <output.swift>
//!
//! Service and method numbers are taken from upstream's own
//! `anki_proto_gen::get_services`, the same helper the core uses to dispatch
//! calls, so they always match the built library. Nothing is numbered by hand.

use std::env;
use std::fmt::Write as _;
use std::fs;

use anki_proto_gen::get_services;
use anki_proto_gen::BackendService;
use anyhow::Context;
use anyhow::Result;
use prost_reflect::DescriptorPool;

fn main() -> Result<()> {
    let args: Vec<String> = env::args().collect();
    let [_, descriptors, output] = args.as_slice() else {
        anyhow::bail!("usage: hayaki_codegen <descriptors.bin> <output.swift>");
    };
    let bytes = fs::read(descriptors).with_context(|| format!("reading {descriptors}"))?;
    let pool = DescriptorPool::decode(bytes.as_slice()).context("decoding descriptor set")?;
    let (_, services) = get_services(&pool);
    let swift = render_methods(&services);
    if fs::read_to_string(output).ok().as_deref() != Some(swift.as_str()) {
        fs::write(output, swift).with_context(|| format!("writing {output}"))?;
    }
    Ok(())
}

fn render_methods(services: &[BackendService]) -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by core/codegen from the Anki core's descriptor set. Do not edit.\n\
         // Regenerate with scripts/build-core.sh.\n\n\
         /// One method of the Anki core, addressed by the numbers the core dispatches on.\n\
         public struct CoreMethod: Sendable, Hashable, CustomStringConvertible {\n    \
         public let service: UInt32\n    \
         public let method: UInt32\n    \
         public let name: String\n\n    \
         public var description: String { name }\n}\n\n\
         extension CoreMethod {\n",
    );
    for service in services {
        let service_name = service.name.trim_start_matches("Backend");
        let service_name = service_name.trim_end_matches("Service");
        writeln!(out, "    public enum {service_name} {{").unwrap();
        for method in service.all_methods() {
            writeln!(
                out,
                "        public static let {swift_name} = CoreMethod(service: {service_index}, method: {method_index}, name: \"{service_name}.{proto_name}\")",
                swift_name = lower_camel(method.proto.name()),
                service_index = service.index,
                method_index = method.index,
                proto_name = method.proto.name(),
            )
            .unwrap();
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    out
}

fn lower_camel(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_lowercase().chain(chars).collect(),
        None => String::new(),
    }
}
